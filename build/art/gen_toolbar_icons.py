    [("M12 5.5l2.3 4.6 5.1.7-3.7 3.6.9 5-4.6-2.4-4.6 2.4.9-5-3.7-3.6 5.1-.7z", "fg")],  # 2 favorites
    [("M10.5 5.5l2 4.1 4.5.6-3.3 3.2.8 4.5-4-2.1-4 2.1.8-4.5-3.3-3.2 4.5-.6z", "fg"),
     ("M19 15.5v4.5M16.75 17.75h4.5", "fg")],                               # 3 add to favorites
